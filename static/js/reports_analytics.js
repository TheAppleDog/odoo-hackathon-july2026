/* Reports & Analytics page JS (Chart.js + CSV export) */

(function () {
  const $ = (id) => document.getElementById(id);

  const startDateEl = $('raStartDate');
  const endDateEl = $('raEndDate');
  const vehicleFilterEl = $('raVehicleFilter');

  const noticeEl = $('raExportNotice');
  const exportPdfBtn = $('exportPdfBtn');
  const exportCsvBtn = $('exportCsvBtn');

  // KPI elements
  const kpiTotalTrips = $('kpiTotalTrips');
  const kpiFleetUtilization = $('kpiFleetUtilization');
  const kpiFuelExpenses = $('kpiFuelExpenses');
  const kpiMaintenanceCost = $('kpiMaintenanceCost');

  // CSV
  function downloadTextFile(filename, mime, text) {
    const blob = new Blob([text], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  }

  function exportCSV() {
    const start = startDateEl?.value || '';
    const end = endDateEl?.value || '';
    const vehicle = vehicleFilterEl?.value || 'all';

    const sampleRows = [
      ['trip_id', 'date', 'vehicle', 'driver', 'distance_km', 'fuel_cost', 'maintenance_cost'],
      ['TR100', '2026-07-12', 'MH01AB1234', 'Rahul Sharma', '142', '3950', '2500'],
      ['TR101', '2026-07-13', 'GJ05CD7890', 'Priya Patel', '96', '6100', '4500'],
      ['TR103', '2026-07-12', 'GJ01PQ1111', 'Neha Verma', '155', '5120', '12000'],
      ['TR105', '2026-07-12', 'GJ18UV3333', 'Riya Shah', '84', '1420', '3200'],
    ];

    const meta = `# Export generated by TransitOps Reports & Analytics\n# Date Filter: ${start} to ${end}\n# Vehicle: ${vehicle}\n`;
    const csv = meta + sampleRows.map((r) => r.join(',')).join('\n');

    downloadTextFile('transitops-reports.csv', 'text/csv;charset=utf-8', csv);
  }

  function showNotice() {
    if (!noticeEl) return;
    noticeEl.style.display = 'block';
    setTimeout(() => {
      if (noticeEl) noticeEl.style.display = 'none';
    }, 4500);
  }

  exportPdfBtn?.addEventListener('click', () => {
    showNotice();
  });

  exportCsvBtn?.addEventListener('click', () => {
    exportCSV();
  });

  // Chart helpers
  function ctx(id) {
    return $(id);
  }

  function initCharts() {
    // Monthly Trips (Bar)
    const monthlyTripsCanvas = ctx('raMonthlyTripsChart');
    if (monthlyTripsCanvas && window.Chart) {
      new Chart(monthlyTripsCanvas, {
        type: 'bar',
        data: {
          labels: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun'],
          datasets: [
            {
              label: 'Trips',
              data: [48, 52, 55, 61, 58, 64],
              backgroundColor: '#714B67',
              borderRadius: 12,
              maxBarThickness: 28,
            },
          ],
        },
        options: {
          responsive: true,
          plugins: { legend: { display: false } },
          scales: {
            x: { grid: { display: false }, ticks: { color: '#675263' } },
            y: {
              grid: { color: 'rgba(113,75,103,0.08)' },
              ticks: { color: '#675263' },
              suggestedMax: 80,
            },
          },
        },
      });
    }

    // Fuel Cost Trend (Line)
    const fuelTrendCanvas = ctx('raFuelCostTrendChart');
    if (fuelTrendCanvas && window.Chart) {
      new Chart(fuelTrendCanvas, {
        type: 'line',
        data: {
          labels: ['2026-02', '2026-03', '2026-04', '2026-05', '2026-06', '2026-07'],
          datasets: [
            {
              label: 'Fuel Cost',
              data: [24800, 27150, 26590, 29940, 31880, 34220],
              borderColor: '#714B67',
              backgroundColor: 'rgba(113,75,103,0.12)',
              tension: 0.35,
              fill: true,
              pointRadius: 4,
              pointHoverRadius: 6,
            },
          ],
        },
        options: {
          responsive: true,
          plugins: { legend: { display: false } },
          scales: {
            x: { grid: { display: false }, ticks: { color: '#675263' } },
            y: {
              grid: { color: 'rgba(113,75,103,0.08)' },
              ticks: { color: '#675263' },
              callback: (value) => '₹' + value,
            },
          },
        },
      });
    }

    // Vehicle Status (Doughnut)
    const vehicleStatusCanvas = ctx('raVehicleStatusChart');
    if (vehicleStatusCanvas && window.Chart) {
      new Chart(vehicleStatusCanvas, {
        type: 'doughnut',
        data: {
          labels: ['Active', 'On Trip', 'Maintenance', 'Inactive'],
          datasets: [
            {
              data: [62, 24, 9, 5],
              backgroundColor: ['#714B67', '#5A8FD4', '#E06A88', '#B8B0C0'],
              borderWidth: 0,
              hoverOffset: 10,
            },
          ],
        },
        options: {
          cutout: '65%',
          plugins: { legend: { display: false } },
          responsive: true,
          maintainAspectRatio: false,
        },
      });
    }

    // Maintenance Distribution (Pie)
    const maintPieCanvas = ctx('raMaintenanceDistributionChart');
    if (maintPieCanvas && window.Chart) {
      new Chart(maintPieCanvas, {
        type: 'pie',
        data: {
          labels: ['Oil Change', 'Brake Inspection', 'Engine Service', 'Tyre Replacement'],
          datasets: [
            {
              data: [18, 22, 9, 11],
              backgroundColor: ['#714B67', '#9E7A97', '#5A8FD4', '#B8B0C0'],
              borderWidth: 0,
              hoverOffset: 10,
            },
          ],
        },
        options: {
          plugins: { legend: { display: false } },
          responsive: true,
          maintainAspectRatio: false,
        },
      });
    }
  }

  // KPIs - sample computed values
  function initKPIs() {
    // Use filter presence lightly for visual responsiveness; keep realistic sample values.
    const vehicle = vehicleFilterEl?.value || 'all';
    const isAll = vehicle === 'all';

    const trips = isAll ? 220 : 47;
    const util = isAll ? 74 : 69;
    const fuel = isAll ? 861200 : 189500;
    const maint = isAll ? 64200 : 15600;

    kpiTotalTrips.textContent = trips;
    kpiFleetUtilization.textContent = util + '%';
    kpiFuelExpenses.textContent = '₹' + fuel.toLocaleString('en-IN');
    kpiMaintenanceCost.textContent = '₹' + maint.toLocaleString('en-IN');
  }

  function wireFilters() {
    const handler = () => {
      initKPIs();
      // Charts remain sample for now (no PDF/DB integration requested).
    };
    startDateEl?.addEventListener('change', handler);
    endDateEl?.addEventListener('change', handler);
    vehicleFilterEl?.addEventListener('change', handler);
  }

  window.addEventListener('DOMContentLoaded', () => {
    initCharts();
    initKPIs();
    wireFilters();
  });
})();

